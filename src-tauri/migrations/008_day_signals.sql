-- v8(E23) — 하루 신호 원장. **'정적(quiet)의 설계'가 기다리던 단 하나의 미지수**를 잰다.
--
-- 오늘 탭 하단 스트립은 all-clear 인 날에도 `마감 임박 없음`·`열린 보충 0 건`·`의식 ☐ ☐` 을
-- 그렸다(E8 이 그걸 고쳐 "말할 것이 있을 때만" 그리게 했다). 그런데 그 변경의 값어치는
-- **all-clear 가 얼마나 자주 오는가**에 달려 있다 — 거의 안 오면 금도금이고, 자주 오면 매일
-- 0의 벽을 치우는 것이다. 로드맵은 그 항목을 "빈도 미측정"으로 Later 에 묶어 뒀고, 그건
-- 아이디어 부족이 아니라 계기 부족이다(007 이 IA 결정에 대해 같은 진단을 받았다).
--
-- ## 왜 파생이 아니라 표인가
--
-- 이 값들은 전부 앱 상태에서 계산되지만 **그날그날의 상태는 남지 않는다**. `completions` 는
-- 완료를 남기고 `backlog` 는 현재 열린 것만 들며, "그날 마감이 몇 건 임박해 있었나"는 지나가면
-- 재구성이 불가능하다(항목이 지워지거나 마감이 바뀌면 과거가 소급해 달라진다). 관측은 관측된
-- 시점에 남겨야 관측이다.
--
-- ## 한 날에 한 행 — 마지막으로 본 값이 이긴다
--
-- 값은 하루 동안 변한다(블록을 끝내면 pending 이 준다). upsert 로 **마지막 관측**을 남기는데,
-- 그것이 "하루가 어떻게 끝났나"에 가장 가깝기 때문이다. 정오에 앱을 닫으면 정오의 값이 남고,
-- 그건 거짓이 아니라 **그날 마지막으로 관측된 사실**이다.
--
-- ## 동기화 대상이 아니다 — 구조적으로
--
-- `updated_at` 열이 없다. 아웃박스는 그 열로 수집하므로(004) 열이 없으면 수집 자체가 표현
-- 불가능하다 — 플래그로 거르는 것과 다르다(플래그는 누가 뒤집을 수 있다). 007 과 같은 판단이고,
-- 기기마다 다른 값이 나오는 것이 정상이라는 점에서도 같다(폰과 PC 의 '오늘'은 같은 날이어도
-- 관측 시점이 다르다).
--
-- ⚠ D1 에도 같은 DDL 이 가서 **빈 테이블 하나가 생긴다**. 스키마를 갈래내는 것보다 잉여
-- 테이블이 싸다는 v5 의 판정을 그대로 따른다(런북 §3-2 · 필터하지 말고 소비 측에서 거른다).
--
-- 열 이름은 오늘 탭의 스트립 입력 그대로다 — 나중에 "무엇을 쟀나"를 되짚을 때 화면과 표가
-- 같은 어휘를 쓰는 것이 중요하다(이 표의 독자는 몇 주 뒤의 우리다).
CREATE TABLE day_signals (
    ds TEXT PRIMARY KEY,
    -- 그날 남아 있던 미완료 학습 블록 수
    pending INTEGER NOT NULL DEFAULT 0,
    -- 밀린(overdue) 복습 챕터 수
    overdue INTEGER NOT NULL DEFAULT 0,
    -- 열린 보충 건수
    backlog INTEGER NOT NULL DEFAULT 0,
    -- Anki 오늘 due(미연결이면 -1 — 0 과 구분한다: 없음 ≠ 모름)
    anki_due INTEGER NOT NULL DEFAULT -1,
    -- 14일 내 임박 마감 과목 수
    due_soon INTEGER NOT NULL DEFAULT 0
);
