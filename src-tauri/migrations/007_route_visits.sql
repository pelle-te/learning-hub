-- v7(N-11) — 방문 원장. **관측이 없어 결정하지 못한 것**을 재기 위한 로컬 카운터.
--
-- 이 앱은 25탭 중 무엇을 실제로 여는지 자기 자신을 모른다(`shell/recent.ts` 는 팔레트 명령
-- LRU 뿐이고 텔레메트리는 에러만 보낸다). 그 공백 위에 IA 결정 셋이 서 있었다 — 탭 은퇴 근거,
-- 폰 review 뷰 사용 여부, all-clear 빈도. 세 각도가 독립적으로 "관측이 없어 결정 불가"에서
-- 멈췄고(2026-07-25 발산), 그건 아이디어 부족이 아니라 계기 부족이다.
--
-- ## ⚠ 진입 경로(`via`)로 쪼개는 것이 이 표의 핵심이다
--
-- 방문 수는 **가치가 아니라 접근성의 함수**다. 레일에 있으니 눌리고, 숨겨 뒀으니 안 눌린다.
-- 합계만 세면 _숨겨서 안 쓰이게 만든 것을 안 쓰인다고 지우는_ 순환에 빠진다 — 그 순환은
-- 데이터가 있다는 이유로 더 자신 있게 틀린다. 그래서 (key, day, via) 가 기본키다:
-- 레일을 지웠을 때 ⌘K·딥링크 방문이 남는지가 "필요한가"의 진짜 신호다.
--
-- ## 동기화 대상이 아니다 — **구조적으로**
--
-- `updated_at` 열이 없다. 아웃박스는 그 열로 수집하므로(004) 열이 없으면 수집 자체가
-- 표현 불가능하다 — 플래그로 거르는 것과 다르다(플래그는 누가 뒤집을 수 있다).
-- `runtime_cache`·`meta` 가 같은 이유로 v3 에서 빠졌다. 또한 `settings` 를 재사용하지
-- 않는다: 거기는 `rows.ts` 매퍼가 통째로 소유해 **모르는 키를 지운다**(전량 대조가 그 계약).
--
-- ⚠ D1 에도 같은 DDL 이 가서 **빈 테이블 하나가 생긴다**. 스키마를 갈래내는 것보다 잉여
-- 테이블이 싸다는 v5 의 판정을 그대로 따른다(런북 §3-2 · 필터하지 말고 소비 측에서 거른다).
--
-- 인덱스는 보존기간 청소(`day < ?`)와 구간 조회용이다. 이 표는 UI 가 붙기 전에도 매
-- 내비게이션마다 쓰이므로, 청소가 풀스캔이면 그 비용이 사용자 입력 경로에 앉는다.
CREATE TABLE route_visits (
    key TEXT NOT NULL,
    day TEXT NOT NULL,
    via TEXT NOT NULL,
    n INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (key, day, via)
);

CREATE INDEX idx_route_visits_day ON route_visits (day);
