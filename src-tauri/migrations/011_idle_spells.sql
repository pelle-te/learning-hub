-- v11(W3 · 발산 6회차) — **유휴 원장**(N-8). "PC 앞인데 5분째 무입력"이 하루에 몇 번,
-- 몇 시에 일어나는가.
--
-- ## ⚠⚠ 이 표는 알림을 쏘기 위한 것이 아니다 — **전제를 재기 위한 것**이다
--
-- N-8(재수신성 트리거)의 전제는 *앱이 떠 있는 채로 사람이 자리를 비우거나 다른 창에서
-- 일하는 구간이 실재한다* 이다. 그런데 그 전제의 근거로 인용되던 실측(T-3 의 _"사용자는
-- 켜 놓고 살지 않는다"_)은 **트레이·자동시작이 생기기 전** 것이라 지금은 유효하지 않다.
-- 로드맵이 적은 가장 싼 검증이 그래서 _"알림 0으로 3일 유휴 로그만"_ 이다 — 개입을 먼저
-- 붙이면, 전제가 틀렸을 때 남는 것은 알림 피로뿐이고 그건 되돌리기 어렵다.
--
-- ## 왜 홉 원장(010)에 열을 더하지 않나
--
-- 010 의 행은 **내비게이션 사건**이고 여기 행은 **부재 구간**이다. 같은 표에 넣으면
-- `n` 의 단위가 섞이고(홉 수 ↔ 구간 수) 010 의 기본키에 유휴가 낄 자리도 없다.
-- 007→010 이 이미 같은 판정을 내렸다: _"스키마를 갈래내는 것보다 잉여 테이블이 싸다"_.
--
-- ## 무엇을 세는가 — **임계를 넘은 순간**과 **그 구간의 길이**
--
-- `n` = 유휴가 임계(프런트의 `IDLE_MIN_SEC`)를 넘은 횟수. 그 순간이 곧 개입이 발사됐을
-- 시각이라, `hour` 는 **임계를 넘은 시각**이지 구간이 끝난 시각이 아니다.
-- `sec` = 그 구간들의 총 길이. 두 값이 함께 있어야 "짧게 자주"와 "길게 드물게"가 갈린다 —
-- 전자면 트리거가 방해가 되고 후자면 값이 있다.
--
-- ⚠ **`updated_at` 이 없다 = 동기화 대상이 아니다**(007·008·010 과 같은 형태). 아웃박스는
-- 그 열로 수집하므로 열이 없으면 수집이 표현 불가능하다. 그리고 유휴는 **그 기계의 사실**이라
-- 기기 간에 합치면 뜻이 없어진다(폰이 잠긴 것과 PC 앞을 뜬 것은 같은 값이 아니다).
-- ⚠ `hour` 는 로컬 시각이다(010 과 같은 이유 — 질문이 "사용자의 하루 어디쯤인가"다).
CREATE TABLE idle_spells (
    day TEXT NOT NULL,
    hour INTEGER NOT NULL,
    n INTEGER NOT NULL DEFAULT 0,
    sec INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (day, hour)
);

CREATE INDEX idx_idle_spells_day ON idle_spells (day);
