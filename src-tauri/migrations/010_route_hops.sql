-- v10(W2 · 발산 6회차) — **홉 원장**. 007 이 "어디를 열었나"를 셌다면 여기는 **"무엇 다음에
-- 무엇을 열었나"** 와 **"몇 시에"** 를 센다.
--
-- ## 왜 007 로는 안 되나 (열을 더하지 않고 표를 하나 더 두는 이유)
--
-- 007 의 기본키는 `(key, day, via)` 다. 여기에 `from_key`·`hour` 를 더하려면 기본키를 바꿔야
-- 하고, 그러면 **이미 쌓인 행의 뜻이 달라진다**(같은 키가 시각별로 쪼개져 옛 합계와 새 합계가
-- 다른 단위가 된다). 007 의 머리주석이 이미 그 판정을 내려 뒀다: _"스키마를 갈래내는 것보다
-- 잉여 테이블이 싸다"_(v5). 같은 자를 여기에도 쓴다.
--
-- ## 이 표가 답하는 질문 셋 (전부 지금 결정을 막고 있는 것들)
--
-- ① **두 페인이 값어치 있나** — `A → B → A` 왕복쌍이 실제로 있나, 아니면 롱테일인가.
--    "이걸 보면서 저걸 한다"는 개념이 이 앱엔 아예 없는데(라우터가 하나다), 그것을 만들지
--    말지는 왕복이 실재하는지에 달렸다. 롱테일이면 안 만드는 것이 답이고 **그 사실도 산출**이다.
-- ② **조명이 상수인가** — 하루 중 앱을 여는 시각이 퍼져 있나, 한 번에 몰리나. 몰리면
--    "캔버스가 하루의 위치를 싣는다"는 안은 값이 0이다(같은 시각에만 보므로 늘 같은 조도).
-- ③ **저녁에 앱을 여나** — 저녁판(내일 확정)과 아침판(아침 결정) 중 어느 쪽이 맞는지가
--    18~24시 방문 비율 하나로 갈린다.
--
-- ⚠⚠ **셋 다 "안 만든다"가 정당한 답이 될 수 있는 질문이다.** 그래서 계측이 먼저다 —
-- 이 저장소는 관측을 기다리면서 관측 장치를 안 다는 순환에 T-5·T-8·T-10 에서 이미 물렸다.
--
-- ## 동기화 대상이 아니다 — **구조적으로**(007·008 과 같은 형태)
--
-- `updated_at` 열이 없다. 아웃박스는 그 열로 수집하므로(004) 열이 없으면 수집 자체가
-- 표현 불가능하다 — 플래그로 거르는 것과 다르다(플래그는 누가 뒤집을 수 있다).
-- ⚠ D1 에도 같은 DDL 이 가서 빈 표가 하나 생긴다. 007 의 판정을 그대로 따른다.
--
-- ## ⚠ `hour` 는 로컬 시각이다(UTC 아님)
--
-- 이 표가 답하려는 것이 **"사용자의 하루 어디쯤인가"** 라 UTC 로 저장하면 질문 자체가 깨진다.
-- 대신 여행·서머타임에서 값이 흔들리는데, 그 정밀도는 여기 필요 없다(버킷이 시간 단위다).
--
-- 인덱스는 보존기간 청소(`day < ?`)와 구간 조회용 — 007 과 같은 이유로 풀스캔을 피한다.
CREATE TABLE route_hops (
    from_key TEXT NOT NULL,
    to_key TEXT NOT NULL,
    day TEXT NOT NULL,
    hour INTEGER NOT NULL,
    n INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (from_key, to_key, day, hour)
);

CREATE INDEX idx_route_hops_day ON route_hops (day);
