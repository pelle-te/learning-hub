let 실패 = false;
let 모름 = 0;
/** 각 축이 실제로 나빴는가 — 아래 역래칫이 읽는다. 관측 못 한 축은 키가 없다(= 모름). */
const 본 = {};
console.log('=== 신선도(기대 주기) ===');
for (const 행 of 경로들) {
  let r = null;
  try {
    r = 행.재기();
  } catch (e) {
    console.log(`  – ${행.이름}: 잴 수 없음(${e instanceof Error ? e.message : e})`);
    모름++;
    continue;
  }
  if (r === null) {
    console.log(`  – ${행.이름}: 관측 불가(gh/git 없음 또는 인증 없음) — 「괜찮다」가 아니라 「모른다」다`);
    모름++;
    continue;
  }
  const 늦음 = r.지연일 > 행.하한일;
  const 나쁨 = 늦음 || r.즉시실패;
  const 면제 = 보류[행.이름];
  const 만료 = 면제 && Date.parse(면제.재검토) < 지금;
  본[행.이름] = 나쁨;
  console.log(
    `  ${나쁨 ? (면제 && !만료 ? '⏳' : '❌') : 'ok'} ${행.이름}: ${r.지연일}일 (하한 ${행.하한일}일) · ${r.상세}${r.즉시실패 ? ` · ${r.즉시실패}` : ''}`,
  );
  if (나쁨 && 면제 && !만료) {
    console.log(`      ⏳ 보류(재검토 ${면제.재검토}) — ${면제.사유}`);
    continue;
  }
  if (나쁨 && 만료) {
    console.error(`      ❌ 보류가 만료됐다(${면제.재검토}) — 판단을 갱신하거나 고쳐라.`);
    실패 = true;
    continue;
  }
  if (나쁨) 실패 = true;
}

/* ③ 역래칫 — 지연이 사라졌는데 원장에 남아 있으면 실패. 원장이 실물과 갈리면 다음 사람이
   «이건 원래 있던 거겠지» 하고 넘긴다(`audit-gate.mjs` 가 같은 근거로 같은 검사를 갖는다). */
for (const [이름, 면제] of Object.entries(보류)) {
  if (본[이름] === false) {
    console.error(`❌ 보류 항목 「${이름}」이 이미 해소됐다 — 원장에서 지워라(사유: ${면제.사유.slice(0, 40)}…).`);
    실패 = true;
  }
}

if (모름) console.log(`\n⚠ ${모름}개 축을 관측하지 못했다 — 이 실행은 그만큼 덜 봤다.`);
if (실패) {
  console.error('\n❌ 기대 주기를 넘긴 경로가 있다.');
  console.error('   → 고치거나, **원장에 «지금 안 하는 이유 + 재검토일»을 적어라**(SCA 원장과 같은 규율).');
  console.error('   → 이 표의 하한이 현실과 안 맞으면 값을 고쳐라. 단 **왜 고치는지 함께 적는다.**');
  process.exit(1);
}
console.log('\n✅ 기대 주기 안.');
