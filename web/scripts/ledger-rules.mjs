/**
 * @typedef {{ 사유: string, 재검토: string }} 원장항목
 * @typedef {Record<string, 원장항목>} 원장
 */

/**
 * 기한부 판단 원장을 실물과 대조한다.
 *
 * @param {object} 입력
 * @param {원장} 입력.원장       키 → { 사유, 재검토(YYYY-MM-DD) }
 * @param {Record<string, boolean>} 입력.상태  키 → **지금 위반인가**. ⚠ 원장 키가 여기 없으면
 *   「관측하지 않았다」로 본다(③을 안 울린다) — 관측 못 한 것을 «해소됐다»로 읽으면
 *   원장이 조용히 비워진다. 「모른다」와 「괜찮다」를 가르는 것이 이 저장소의 규율이다.
 * @param {string} [입력.오늘]   YYYY-MM-DD (기본: 오늘)
 * @returns {{ 만료: string[], 사문: string[], 적용: string[], ok: boolean }}
 *   · `만료` — ②를 어긴 키(재검토일이 지났는데 아직 위반)
 *   · `사문` — ③을 어긴 키(해소됐는데 원장에 남음)
 *   · `적용` — 아직 유효한 면제(호출부가 이만큼 위반을 삼켜도 된다)
 */
export function 원장판정({ 원장, 상태, 오늘 = new Date().toISOString().slice(0, 10) }) {
  const 만료 = [];
  const 사문 = [];
  const 적용 = [];
  for (const [키, 항목] of Object.entries(원장)) {
    const 지금위반 = 상태[키];
    if (지금위반 === undefined) continue; // 관측 안 함 — 판정 보류(위 ⚠)
    if (!지금위반) {
      사문.push(키);
      continue;
    }
    if (항목.재검토 < 오늘) 만료.push(키);
    else 적용.push(키);
  }
  return { 만료, 사문, 적용, ok: 만료.length === 0 && 사문.length === 0 };
}

/** 실패 메시지 — 네 원장이 같은 문장을 쓰게 한다(형식이 갈리면 읽는 법도 갈린다). */
export function 원장메시지(이름, { 만료, 사문 }, 원장) {
  const 줄 = [];
  for (const k of 만료)
    줄.push(`  ❌ ${k} — 재검토 기한 ${원장[k].재검토} 이 지났다. 고치거나, 다시 판단하고 날짜를 갱신하라.`);
  for (const k of 사문)
    줄.push(
      `  ❌ ${k} — 이미 해소됐는데 원장에 남아 있다(역래칫). 지워라 — 남으면 새 위반이 그 아래로 조용히 들어간다.`,
    );
  return `${이름} 원장이 실물과 갈렸다(${만료.length + 사문.length}건):\n${줄.join('\n')}\n`;
}
