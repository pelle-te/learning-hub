export interface NavGroup {
  key: string;
  /** 레일 헤더 문구 — **질문**이다(N-16). 분류명이 아니다. */
  label: string;
  tabs: TabMeta[];
}

/** 레일에 **설 수 있는** 것 전부 — `destination` + `lens`(N-14 평탄화). 은퇴·명사는 안 선다.
 *  ⚠ *설 수 있는* 이다: 사용자가 접은 것(N-17)은 여기 남아 있고 그리기 직전에 빠진다
 *  (`shell/railLayout`). 숨김은 도달성이 아니라 표시의 문제라 로스터를 안 건드린다. */
function railCandidates(): TabMeta[] {
  return TABS.filter((t) => t.role === 'destination' || t.role === 'lens');
}

function buildNavGroups(): NavGroup[] {
  const byKey = new Map(railCandidates().map((t) => [t.key, t]));
  const groups: NavGroup[] = [];
  for (const sec of RAIL_SECTIONS) {
    const tabs = sec.tabs.map((k) => byKey.get(k)).filter((t): t is TabMeta => !!t);
    if (tabs.length) groups.push({ key: sec.key, label: sec.question, tabs });
  }
  /* ⚠ 섹션에 안 적힌 레일 탭은 **잃지 않는다** — 마지막 섹션 뒤에 붙이고, 불변식이 그 사실을
     따로 잡는다. 조용히 사라지는 것이 이 파일이 반복해서 막아 온 실패다(`graph` 가 배열에서
     빠지며 ⌘K 에서 사라진 그 형태). */
  const placed = new Set(groups.flatMap((g) => g.tabs.map((t) => t.key)));
  const orphans = railCandidates().filter((t) => !placed.has(t.key));
  if (orphans.length) groups.push({ key: 'unplaced', label: '섹션 미지정', tabs: orphans });
  return groups;
}
const NAV_GROUPS: NavGroup[] = buildNavGroups();
export function navGroups(): NavGroup[] {
  return NAV_GROUPS;
}

/** `[ ]` 링이 도는 목록 — **레일에 보이는 순서 그대로**(그룹 순 → 그룹 안 order 순).
 *
 *  ⚠ 레일 순서에서 **파생**시키는 것이 핵심이다. 한때 이 함수가 `ORDERED_TABS` 를 직접 필터해
 *  두 목록의 *멤버십*은 같은데 *순서*가 달랐다(그룹 순서를 빈도 위계로 고정한 순간 갈렸다).
 *  그러면 `]` 를 눌렀을 때 레일에서 아래가 아닌 엉뚱한 칸으로 튄다 — 눈에 보이는 순서와 손이
 *  기대하는 순서가 어긋나는, 설명 없이는 못 알아채는 부류다. 이제 두 벌이 될 수 없다.
 *  (`test/invariants.test.ts` 가 같은 목록임을 계속 잠근다 — 이 파생이 뒤집히면 즉시 빨개진다.) */
const RAIL_TABS: TabMeta[] = NAV_GROUPS.flatMap((g) => g.tabs);
/** ⚠ 옛 이름은 `destinations()` 였다 — N-14 전에는 레일 = destination 이라 두 뜻이 같았는데,
 *  평탄화 뒤에는 **렌즈도 레일에 선다**. 이름이 `destination` 이면 이 목록을 쓰는 곳마다
 *  "왜 렌즈가 여기 있지"를 다시 물어야 하고, 그게 곧 다음 사람의 오독이다. */
export function railTabs(): TabMeta[] {
  return RAIL_TABS;
}

/* ⚠⚠ **`subTabGroupOf`·`hostTabKey` 가 여기 있었다 — 세그먼트 바와 함께 은퇴했다**(N-14 · W5).
   둘의 존재 이유는 *"이 렌즈는 어느 호스트 밑인가"* 였고, 평탄화가 그 질문 자체를 없앴다(모든
   화면이 레일에 자기 줄을 갖는다 → 활성 표기도 링 인덱스도 **자기 자신**이다).
   ⚠ `lastLens`(호스트별 마지막 렌즈 기억 · E27)도 같은 이유로 사라졌다: 그건 두 층 구조가
   만든 2클릭을 덧대던 장치였고, 층이 하나면 덧댈 것이 없다.
   되살리려면 `git show e0ed394:web/src/shell/tabs.ts`. */

/** key 가 속한 **레일 섹션 key**(없으면 자기 자신 — 섹션 밖 화면도 방향 판정이 필요하다).
 *  ⚠ 소비처는 `vt.ts` 하나다: 같은 질문 안의 이동인지 다른 질문으로 넘어가는지를 가른다. */
export function sectionOf(key: string): string {
  return RAIL_SECTIONS.find((s) => s.tabs.includes(key))?.key ?? key;
}

/** 표시 순서대로 정렬된 탭(모듈 로드 시 1회 계산된 상수 반환 — 제자리 변형 금지). */
export function orderedTabs(): TabMeta[] {
  return ORDERED_TABS;
}
export function tabByKey(key: string): TabMeta | undefined {
  return TAB_BY_KEY.get(key);
}

/* ⚠⚠ **여기 `ROUTE_LABELS` 라는 두 번째 이름표 표가 있었다 — A-7 이 없앴다**(2026-08-07).

   H27(2026-07-31)이 고친 문제는 옳았다: `/subject/:id`·`/mini` 는 탭이 아니라 `tabByKey` 가
   `undefined` 를 줬고, 그래서 라우트 아나운서가 **무음**이고 문서 제목이 `러닝허브` 로 굳었다.
   틀린 것은 처방이었다 — **표를 하나 더 판 것**. 그 순간 이 함수는 표 둘을 순서대로 뒤지는
   함수가 됐고, 새 명사 주소가 생길 때마다 *어느 표에 적을지*를 사람이 고르게 됐다. D-4 가
   "갈 수 있는 곳"의 다섯 열거를 하나로 되돌린 그 문제가 **이름 축에서 재발**한 것이다.

   당시 그러지 않은 이유(_"`TABS` 에 넣으면 레일·링·`g`·`primary` 불변식이 전부 따라온다"_)는
   **역할 어휘가 없을 때만** 참이었다. 지금은 그 열거들이 전부 `role` 에서 파생하므로,
   `role:'object'` 는 어디에도 안 따라 들어간다(`ORDERED_TABS` 가 그 파생의 첫 관문이다). */

/** 라우트 첫 세그먼트 → 사람이 읽는 이름. 로스터에 없으면 빈 문자열(표는 하나다). */
export function routeLabelOf(key: string): string {
  return TAB_BY_KEY.get(key)?.label ?? '';
}

/** 명사 주소 전부(`role:'object'`) — `App` 이 라우트를 그릴 때 순회한다. */
export function objectRoutes(): TabMeta[] {
  return TABS.filter((t) => t.role === 'object');
}

/**
 * **경로 + 쿼리** → 사람이 읽는 이름. `?view=` 로 갈라지는 화면까지 본다.
 *
 * ⚠⚠ **W9 이 만든 회귀다**(H-12 · 2026-08-06 감사). W9 은 탭 셋을 호스트의 뷰로 접으면서
 * 도달 경로를 `/degree?view=path` 같은 **쿼리**로 옮겼는데, 아나운서와 문서 제목은 여전히
 * **첫 경로 세그먼트만** 읽었다 → 흡수된 화면으로 가면 스크린리더는 `졸업 계획` 이라 말하고
 * 제목도 그대로다(실제로는 `내 길 지도`). 즉 W9 의 "도달성 손실 0" 약속이 **이름 축에서** 깨져
 * 있었다 — 탭 셋이 통째로 이름을 잃었고, 그건 화면으로는 안 보인다.
 *
 * ⚠ 로스터를 손으로 적지 않는다 — `TABS` 의 `to` 를 그대로 대조한다(은퇴 탭이 늘거나 뷰 값이
 * 바뀌어도 따라온다). `retired` 만 보는 게 아니라 `to` 를 가진 전부를 본다.
 */
export function routeLabelOfLocation(pathname: string, search: string): string {
  return tabOfLocation(pathname, search)?.label ?? routeLabelOf(pathname.split('/')[1] || 'today');
}

/** 경로+쿼리가 **로스터의 어느 탭**인가(`?view=` 로 갈라진 것 포함). 없으면 `undefined`. */
function tabOfLocation(pathname: string, search: string): TabMeta | undefined {
  const view = new URLSearchParams(search).get('view');
  if (!view) return undefined;
  const base = `/${pathname.split('/')[1] || ''}`;
  return TABS.find((t) => t.to === `${base}?view=${view}`);
}

/**
 * **방문 원장이 세는 키**(I034 · 2026-08-22 발상 축).
 *
 * ## ⚠⚠ 은퇴 정책이 자기 근거를 원리적으로 파괴하고 있었다
 *
 * `App` 은 `route_visits.key` 를 `pathname.split('/')[1]` 로 만든다 — **첫 세그먼트만**. 그런데
 * 이 파일의 은퇴 관용구는 화면을 지우는 대신 **호스트의 `?view=` 로 내린다**(W9 이 탭 셋을
 * 그렇게 접었다). 두 규칙을 겹치면 이렇게 된다:
 *
 *   화면을 `?view=` 로 내린다 → 그 화면의 방문이 **호스트 이름으로 집계된다** →
 *   그 화면은 자기 몫의 수를 **다시는 갖지 못한다** → 「관측이 쌓이면 판정한다」가 영원히 안 온다.
 *
 * 즉 흡수된 화면은 살릴 근거도 지울 근거도 얻을 수 없는 상태로 고정된다. H-12 가 **이름 축**
 * 에서 고친 것과 같은 결함이 **관측 축**에 남아 있던 것이다(그때 `routeLabelOfLocation` 이 생겼고,
 * 이 함수는 그 짝이다).
 *
 * ⚠ **카디널리티는 로스터가 묶는다** — 임의의 `?view=` 값을 키로 만들지 않는다. `TABS` 의 `to`
 * 와 정확히 맞는 것만 그 탭의 `key` 가 되고, 나머지는 호스트로 떨어진다. 그래서 이 표의 키
 * 어휘는 언제나 **로스터의 부분집합**이고, 은퇴 규칙이 읽는 어휘와 같다.
 *
 * ⚠ **전환기 90일 동안 호스트 수치가 과소 집계된다** — 어제까지 `degree` 로 세던 방문이 오늘부터
 * `goals`·`degree` 로 갈린다. 이건 결함이 아니라 정정이지만, 그 창 안에서 «호스트가 줄었다»를
 * 은퇴 근거로 읽으면 틀린다. 보존창이 밀어낼 때까지는 **키가 갈린 날짜를 기억하고** 읽어라.
 *
 * ⚠ `routeKey`(fill 프레임·나브 활성·`useMarkSeen`)는 **그대로 호스트**다. 그쪽은 «지금 어느
 * 호스트에 있나»가 맞는 질문이고, 여기는 «무엇을 열었나»가 질문이다. 둘을 한 값으로 합치면
 * 흡수된 화면에서 레일 활성 표기가 꺼진다.
 */
export function visitKeyOfLocation(pathname: string, search: string): string {
  /* ⚠ `??` 가 아니라 `||` 다 — 루트(`/`)의 첫 세그먼트는 `undefined` 가 아니라 **빈 문자열**이라
     `??` 로 쓰면 원장에 빈 키가 들어간다(`routeLabelOfLocation` 이 이미 `||` 인 이유와 같다). */
  return tabOfLocation(pathname, search)?.key ?? (pathname.split('/')[1] || 'today');
}
