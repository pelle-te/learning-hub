import { hostTabKey, subTabGroupOf } from './tabs';

/** 호스트 key → 마지막으로 본 렌즈 key. 모듈 상태(세션 한정 · 위 ⚠). */
const last = new Map<string, string>();

/**
 * 지금 보고 있는 탭을 기억한다. 호스트 자신이면 기억을 **지운다** — 사용자가 조망으로
 * 돌아왔다는 뜻이고, 그 다음 클릭이 조망으로 가는 것이 그 의도에 맞다.
 */
export function noteLens(tabKey: string): void {
  const host = hostTabKey(tabKey);
  if (host === tabKey) last.delete(host);
  else last.set(host, tabKey);
}

/**
 * 레일에서 `hostKey` 를 눌렀을 때 실제로 갈 곳. 기억이 없거나 그 사이 그룹이 바뀌었으면
 * 호스트 자신(= 종전 동작).
 *
 * ⚠ 그룹 멤버십을 **매번 다시 확인**한다 — IA 가 바뀌어 그 렌즈가 다른 호스트로 옮겨가면
 * 기억이 남아 있어도 엉뚱한 곳으로 보내게 된다(이 저장소는 오늘 그 IA 재편을 실제로 했다).
 */
export function railTarget(hostKey: string): string {
  const lens = last.get(hostKey);
  if (!lens) return hostKey;
  const group = subTabGroupOf(hostKey);
  return group?.some((t) => t.key === lens) ? lens : hostKey;
}

/** 테스트 격리용 — 모듈 상태를 비운다. */
export function resetLastLens(): void {
  last.clear();
}
