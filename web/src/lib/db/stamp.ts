/* ============================================================
   db/stamp.ts — 동기화 타임스탬프 발급기(C-1). **로컬에서 단조 증가를 보장한다.**

   ## 왜 `Date.now()` 를 그대로 쓰면 안 되는가

   C-1 은 워터마크를 **재계산 방식**으로 잡는다: 밀어올린 뒤 `watermark = max(보낸 것들의
   updated_at)`. 별도 시퀀스 열이 없어 마이그레이션이 싸다는 게 이 선택의 값이다.

   대가는 설계서 §7 이 정확히 경고한 실패 모드다 — **기기 시계가 뒤로 점프하면**(수동 변경·
   NTP 보정·듀얼부트) 그 뒤의 편집이 `updated_at < watermark` 를 받는다. 그러면 "마지막으로
   보낸 뒤 바뀐 것" 질의에 **영영 안 걸린다.** 실패가 조용하다는 게 최악이다: 앱은 정상으로
   보이고, 저장도 실제로 되고, 다른 기기에만 안 나타난다.

   ## 해법 — 발급 지점을 하나로 모으고 거기서 단조를 강제한다

   `max(Date.now(), 직전 + 1)`. 시계가 앞으로 가면 벽시계를 그대로 쓰고(LWW 비교가 실제
   시각을 반영한다), 뒤로 점프하면 **직전 값 + 1** 로 버틴다. 시계가 회복되면 자연스럽게
   벽시계로 복귀한다 — 영구적인 드리프트를 남기지 않는다.

   ⚠ **부팅 시 `seedStamp()` 가 반드시 먼저 불려야 한다.** 모듈 지역 변수는 프로세스가 죽으면
   0 으로 돌아가므로, 재시작 직후엔 단조성이 DB 에 남은 값과 끊긴다. `boot.ts` 가 DB 의
   `MAX(updated_at)`·`MAX(deleted_at)` 로 씨앗을 심어 그 틈을 메운다.

   ## 이것이 대체하지 **않는** 것

   LWW 비교용 타임스탬프와 "보냈나" 표시를 같은 값이 겸하는 구조는 그대로다(설계서가 지적한
   구조적 위험). 여기서 막는 것은 그 겸직의 **가장 날카로운 결과 하나**뿐이다. 나중에 기기가
   셋 이상이 되거나 서버가 순서를 판정해야 하면 진짜 시퀀스/벡터가 필요해질 수 있다.
============================================================ */

/** 마지막으로 발급한 값. 0 = 아직 발급도 씨앗도 없음. */
let _last = 0;

/**
 * 이미 존재하는 최대 타임스탬프를 알려 준다(부팅 시 DB 에서 읽은 값).
 * 여러 번 불러도 안전하다 — **더 큰 값만 채택**한다.
 */
export function seedStamp(seen: number | null | undefined): void {
  if (typeof seen === 'number' && Number.isFinite(seen) && seen > _last) _last = seen;
}

/** 새 타임스탬프. **직전에 발급한 어떤 값보다도 반드시 크다.** */
export function nextStamp(): number {
  const now = Date.now();
  _last = now > _last ? now : _last + 1;
  return _last;
}

/** 지금까지 발급한 최대값(아웃박스가 상한선 진단에 읽는다). */
export function currentStamp(): number {
  return _last;
}

/**
 * 대량 **최초 이관** 전용 스탬프 배급기 — `chunkSize` 건마다 새 단조 스탬프를 낸다(C1).
 *
 * ⚠ 이관 쓰기는 `diffRows(null, …)` 라 전 행이 **한 번의 쓰기**로 나가고, 그대로 두면 전부
 * 같은 스탬프를 받는다. 그런데 아웃박스는 스탬프 그룹을 **경계에서만** 자를 수 있어서
 * (같은 flush 가 만든 행은 쪼개면 유실 — `capBatch` 주석), 단일 그룹이 `MAX_BATCH_ITEMS`(500)를
 * 넘으면 그 배치가 스키마 상한에 걸려 **영구 차단**된다(수개월 쓴 사용자의 첫 클라우드 연결이
 * 통째로 막히는 무증상 결함). 이관 행은 상대 순서가 무의미하므로, 청크마다 스탬프를 갈아
 * 그룹을 상한 아래로 유지하면 아웃박스가 자연히 다배치로 나눠 보낸다.
 *
 * 발급값은 `nextStamp()` 를 거치므로 단조성·`_last` 갱신이 그대로 유지된다(이후 일반 편집은
 * 이 값들보다 큰 스탬프를 받는다). 일반 flush 는 이 배급기를 쓰지 않는다 — 작아서 문제가 없다.
 */
export function chunkedStamp(chunkSize: number): () => number {
  let issued = 0;
  let current = nextStamp();
  return () => {
    if (issued > 0 && issued % chunkSize === 0) current = nextStamp();
    issued++;
    return current;
  };
}

/** 테스트 전용 — 발급기를 초기 상태로. */
export function _resetStamp(): void {
  _last = 0;
}
