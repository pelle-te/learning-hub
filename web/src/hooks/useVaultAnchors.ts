import { useSyncExternalStore } from 'react';
import { subscribeVaultAnchors, vaultAnchorsVersion } from '@/lib/vaultAnchors';

/** 현재 앵커 버전. 값 자체를 쓸 일은 거의 없다 — **구독이 목적**이다. */
export function useVaultAnchorsVersion(): number {
  return useSyncExternalStore(subscribeVaultAnchors, vaultAnchorsVersion, () => 0);
}
