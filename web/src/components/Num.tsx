/* ============================================================
   components/Num.tsx — **수치 조판 프리미티브**(Q-17 · 2026-08-02).

   앱에 `tabular-nums` 가 119회 있는데 그건 자릿수 정렬만 한다. 값·단위·소수가 같은 크기·중량으로
   서 있어서, 리드아웃 하나를 읽을 때마다 "어디까지가 수인가"를 눈이 다시 판단한다.

   ## 이 컴포넌트가 하는 일은 위계 하나뿐이다

   ```tsx
   <Num value={3} frac={2} unit="h" />     // 3 . 2 h  — 값 / 소수(작게) / 단위(작고 흐리게)
   <Num value={87} unit="%" />             // 87 %
   <Num value="—" />                       // 값 부재도 같은 자리에 선다
   ```

   ⚠⚠ **크기를 정하지 않는다.** 폰트 크기·색·중량은 **호출부가 소유한다**(`className` 으로). 이
   컴포넌트가 정하는 것은 *부속이 값보다 얼마나 작은가*뿐이고, 그 비율은 `em` 이라 44px 앵커에도
   13px 리드아웃에도 같은 비율로 얹힌다. 크기를 여기서 정하면 `CountReadout` 이 겪은 것과 같은
   일이 벌어진다 — 화면마다 다른 크기가 필요해서 결국 호출부가 `!` 로 덮게 된다.
   ⚠ 위계 클래스의 SSOT 는 **`styles/ds.css` 의 `ds-num-*` 절**이다(왜 소수는 안 흐리게 하는지
   등의 근거가 거기 있다). 여기서 값을 다시 적지 않는다 — 두 벌이 되면 표류한다.
   ⚠ `tabular-nums` 는 **여기서 걸지 않는다.** 정렬이 필요한 것은 *열에 쌓인 수*이고 그 판단은
   레이아웃을 아는 호출부만 할 수 있다. 단독 수치에 걸면 자간이 넓어지기만 한다.

   ## 소수는 **문자열로** 받는다

   `frac` 은 `2` 든 `'2'` 든 그대로 소수점 뒤에 붙는다 — `0.20` 과 `0.2` 를 구분해야 하는 자리가
   있기 때문이다(숫자로 받아 나누면 후행 0 이 사라지고, 그건 정밀도를 지우는 것이다).
============================================================ */
import type { ReactNode } from 'react';

export interface NumProps {
  /** 값(정수부). 부재는 `'—'` 처럼 문자열로 준다 — 자리는 남기고 값만 없다는 뜻이다. */
  value: ReactNode;
  /** 소수부(소수점 **없이**). 후행 0 을 지키려고 문자열도 받는다. */
  frac?: string | number;
  /** 단위·접미(%·h·일·개). 값의 부속이라 작고 흐리다. */
  unit?: string;
  /** 바깥 `<span>` 의 클래스 — **크기·색·중량은 여기서 온다**(위 머리주석). */
  className?: string;
}

/** 값 + 소수 + 단위를 한 조판 위계로 세운다. 크기는 호출부 것이고, 비율만 여기 것이다. */
export function Num({ value, frac, unit, className }: NumProps) {
  return (
    <span className={className}>
      {value}
      {frac != null && frac !== '' && <span className="ds-num-frac">.{frac}</span>}
      {unit && <span className="ds-num-unit">{unit}</span>}
    </span>
  );
}
