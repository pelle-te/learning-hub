/* ============================================================
   workspacePaths.test.ts — **화면이 글자 그대로 보여 주는 저장소 경로가 실재하는가**(V040 · 2026-08-28).

   ## 왜 생겼나 — 스냅샷이 원리적으로 못 보는 축

   화면 여섯이 사용자에게 부모 워크스페이스의 경로를 **문구로** 보여 준다(`GuideView` 의 안내 ·
   `Ledger`·`Mastery` 의 「이 값을 만드는 도구」 · `PathView` 의 계약 파일). 그중 하나가 실제로
   낡아 있었다: `pipeline/스타일가이드.md` 는 **없고** 정본은 `pipeline/규약/스타일가이드.md` 다.

   그 오타를 **어떤 게이트도 못 잡았다.** `visual.spec.ts` 의 `find-guide` 는 `#main` 을 통째로
   찍으므로 그 문구가 분명히 프레임 안에 있는데, 옛 문구로도 시각 케이스 **5/5 가 통과한다** —
   세 글자 차이가 `maxDiffPixelRatio 0.005`(1064×~800 에서 약 4,000px) 아래로 **희석**되기
   때문이다. 그 파일 머리주석이 크롬 축에서 이미 같은 기전을 적어 뒀고("전체 페이지 샷에 넣으면
   픽셀이 희석돼 임계 아래로 떨어진다"), 그것이 **본문의 짧은 문구 편집**에도 성립한다는 것이
   이 파일의 발견이다.
   ⛔ 그러니 임계를 조여서 고칠 것이 아니다 — 그러면 전 베이스라인이 flaky 가 된다. **축이 다르다.**

   ## 왜 여기인가 — 「어디서 도는가」에 답한 것

   경로가 가리키는 것은 **부모 워크스페이스**(`pipeline/`·`knowledge/`·`docs/`…)인데 hub 은
   서브모듈이다. 후보 셋 중 이 자리를 골랐고, 나머지 둘을 기각한 근거는 실측이다:

   · ⛔ **부모 CI 가 진다** — `actions/checkout` 의 `submodules` 로는 **못 한다**. hub 은 부모와
     **다른 사설 저장소**(`pelle-te/learning-hub` vs `pelle-te/cowork`)라 워크플로 토큰
     (`contents: read` · 자기 저장소 한정)으로는 못 받아 온다. 별도 PAT 을 심어야 하고, 그건
     Minor 항목 하나를 위해 **다른 사설 저장소를 읽는 토큰**을 CI 에 두는 것이다. 부모의
     `검사.yml` 자신이 *"hub(사설 서브모듈)는 미포함"* 을 설계로 적어 뒀다.
   · ⛔ **경로 목록을 계약 파일로 옮긴다** — 문구의 **두 번째 사본**이 생긴다. 그 사본을 JSX 와
     대조하는 검사가 또 필요하고, 실재를 재는 쪽은 **여전히** 부모가 있는 데서만 돈다. 사본만
     늘고 사각은 그대로다.
   · ✅ **여기(유닛)** — 이 문구가 **틀리는 순간**이 「hub 세션이 JSX 를 고칠 때」이고, 그때 그
     사람은 `npm run verify` 를 돈다. 그리고 **부모가 실재하는 유일한 기계가 그 기계다.**
     이 경로들이 사용자에게 보이는 자리도 거기뿐이다(배포된 hub 은 이 워크스페이스 안에서만 산다).

   ⚠ **대가를 명시한다: CI 커버리지는 0이다.** CI 는 hub 만 체크아웃하므로 부모가 없다.
   그때 이 검사는 **skip 으로 남고 그 사실이 출력에 찍힌다** — `freshness.mjs` 가 못박은 규율
   그대로다(_"관측 불가는 실패가 아니다 … 다만 조용히 건너뛰지는 않는다"_). 「모른다」를
   「괜찮다」로 그리지 않는 것이 요점이고, 그래서 아래 ①은 **부모 없이도 돈다**(공허 방지).
============================================================ */
import { describe, expect, it } from 'vitest';
import { existsSync } from 'node:fs';
import { join, sep } from 'node:path';
import { SRC, sources, strip } from './_sources';

/** 부모 워크스페이스의 최상위 이름들 — 화면은 이 이름으로 시작하는 경로를 글자 그대로 쓴다. */
const 필러 = ['pipeline', 'knowledge', 'survey', 'sources', 'exports', 'docs'] as const;

/* ⚠ 왼쪽 경계가 핵심이다: `web/docs/원장.md` 의 `docs/` 에 걸리면 안 된다. UI 문구의 `docs/` 는
   **부모** `docs/` 이고 주석의 `docs/` 는 hub 자신의 `web/docs/` 인데, 주석은 `sources()` 가
   이미 걷어 주므로 여기 남는 것은 전자뿐이다. */
const 경로패턴 = new RegExp(String.raw`(?<![\w./-])(?:${필러.join('|')})/[^\s"'\`<>)}]*`, 'g');

/** 화면 소스(주석 제거본)에서 워크스페이스 경로 문구 전부 — `{ 경로, 파일들 }`. */
function 화면경로들(): { 경로: string; 파일들: string[] }[] {
  const 표 = new Map<string, Set<string>>();
  for (const { path, code } of sources()) {
    for (const m of code.matchAll(경로패턴)) {
      // 문장 끝의 구두점은 경로가 아니다(`… docs/북극성-비전.md.` 같은 본문 문구).
      const 경로 = m[0].replace(/[.,;·]+$/, '');
      if (!표.has(경로)) 표.set(경로, new Set());
      표.get(경로)!.add(
        path
          .slice(SRC.length + 1)
          .split(sep)
          .join('/'),
      );
    }
  }
  return [...표]
    .map(([경로, 파일들]) => ({ 경로, 파일들: [...파일들].sort() }))
    .sort((a, b) => a.경로.localeCompare(b.경로));
}

/* `hub/web` → `hub` → 워크스페이스 루트. ⚠ hub 을 단독 클론하면(=CI) 이 위는 러너 디렉터리라
   존재하지 않는다 — 그래서 마커로 판정한다. `.workspace.json` 은 부모의 §taxonomy 정본이다. */
const 워크스페이스 = join(process.cwd(), '..', '..');
const 부모있음 = existsSync(join(워크스페이스, '.workspace.json'));

if (!부모있음) {
  console.warn(
    `⚠ 워크스페이스 미검출(${워크스페이스}) — 화면 경로의 **실재는 안 쟀다**(모름, 고장 아님).\n` +
      `   hub 을 단독 체크아웃하면 부모(pipeline/·knowledge/·docs/)가 없다. 재려면 워크스페이스 안에서 돌려라.`,
  );
}

describe('워크스페이스 경로 — 화면 문구가 가리키는 것이 실재하는가 (V040)', () => {
  /* ── ① 공허 방지 — 부모 없이도 돈다 ────────────────────────────────────────
     「위반 0」의 분모를 함께 센다. 스캐너가 조용히 아무것도 못 찾으면 아래 ②는 영원히
     초록이고, 그건 이 파일 전체가 장식이 된다는 뜻이다(a11y 의 미측정 래칫과 같은 사상). */
  it('스캐너가 실제로 화면 경로를 찾는다 — 「0건 통과」를 막는 바닥', () => {
    const 찾은 = 화면경로들();
    /* ⚠ 이건 **래칫이 아니다.** 경로를 정당하게 줄였으면 이 바닥을 내려도 된다 — 지키는 것은
       「스캐너가 살아 있다」 하나다. 실측 13(2026-08-28). */
    expect(찾은.length).toBeGreaterThanOrEqual(8);
  });

  /* ── ②-a 스트리퍼 회귀 — 이 검사를 처음 만들 때 실제로 물린 것 ──────────────
     `exports/*.txt` 의 여는 두 글자를 `strip` 이 **블록 주석 시작**으로 읽어 다음 닫힘까지
     삼켰다. 실측: `GuideView.tsx` 196~220행(25줄)이 `sources()` 를 쓰는 불변식 **전부에게**
     안 보였고, 그 안에 `<Cmd>` 경로 둘과 `<Tab k=…>` 셋이 있었다. 근거는 `_sources.ts`. */
  it('`strip` 이 경로 속 글롭을 블록 주석으로 읽지 않는다', () => {
    /* ⚠ **뒤에 진짜 주석이 와야 재현된다.** 글롭이 연 가짜 블록은 *닫힘을 만나야* 삼키므로,
       닫힘이 없는 조각으로는 옛 제거기도 통과한다 — 첫 픽스처가 그래서 공허하게 초록이었다.
       실물이 정확히 이 형상이다: `GuideView` 는 글롭 24줄 뒤에 JSX 주석을 갖는다. */
    const 원문 = [
      '<Cmd>exports/*.txt</Cmd>',
      '<Cmd>python pipeline/_도구/학습신호.py</Cmd>',
      '{/* 이 줄이 가짜 블록의 닫힘 노릇을 한다 */}',
    ].join('\n');
    expect(strip(원문)).toContain('pipeline/_도구/학습신호.py');
  });

  it('그래도 진짜 블록 주석은 여전히 걷어낸다 — 가드가 제거기를 무력화하지 않았다', () => {
    expect(strip('const a = 1; /* 묘비명 */ const b = 2;')).not.toContain('묘비명');
    expect(strip('{/* JSX 묘비명 */}')).not.toContain('묘비명');
  });

  /* ── ② 실재 — 부모가 있을 때만 잰다(없으면 skip 이 출력에 남는다) ──────────── */
  it.skipIf(!부모있음)('화면이 보여 주는 경로가 전부 워크스페이스에 실재한다', () => {
    const 없는것 = 화면경로들()
      .filter(({ 경로 }) => {
        // 글롭(`exports/*.txt`)은 **디렉터리**까지만 잰다 — 산출물 유무는 사용자 상태이지 계약이 아니다.
        const 대상 = 경로.includes('*') ? 경로.slice(0, 경로.lastIndexOf('/')) : 경로;
        return !existsSync(join(워크스페이스, 대상));
      })
      .map(({ 경로, 파일들 }) => `${경로}  ← ${파일들.join(', ')}`);

    expect(없는것, '화면 문구가 없는 경로를 가리킨다 — 사용자가 그대로 타이핑하면 실패한다').toEqual([]);
  });

  /* ── ③ **접두 없는 스크립트 이름**도 실재를 잰다 (U045 · 2026-08-31) ──────────
     ②의 정규식은 `필러/…` 로 시작하는 것만 본다. 그런데 화면은 명령을 **맨 파일명**으로도
     처방한다(`<Cmd>지식엔진.py build</Cmd>` · `<Cmd>검사.sh --fast</Cmd>`) — 그 형태는
     ②의 그물 밖이라, 부모가 목적을 좁히며 두 스크립트를 지운 2026-08-29 뒤에도 안내 탭은
     **없는 명령 둘을 계속 처방했다.** 사용자는 그대로 터미널에 치고 `can't open file` 을 받는다.
     ⚠ 이건 「검사가 없어서」가 아니라 **「검사의 단위가 굵어서」** 난 결함이다(회차 R2). */
  it.skipIf(!부모있음)('화면이 치라고 시키는 스크립트가 실재한다 — 맨 파일명도 잰다', () => {
    /* 왼쪽 경계는 `[\w가-힣./-]` 부재 — 그래야 `pipeline/_도구/x.py` 의 꼬리를 두 번 세지 않는다
       (그건 ②의 담당이고, 거기서 이미 경로째 실재를 잰다).
       ⚠⚠ **한글을 경계에 넣어야 한다** — JS 의 `\w` 는 ASCII 전용이라 `[\w./-]` 만으로는
       `챕터원장.py` 의 한복판에서 매치가 시작돼(`터원장.py`) **멀쩡한 이름을 없다고 신고한다**.
       이 회차의 리포트가 처방한 정규식이 정확히 그 형태였고, 실물에 돌리자마자 위반 2건을
       거짓으로 냈다(회차 R2 의 자기 예시 — 「단위가 굵다」는 처방 쪽에도 성립한다). */
    const 스크립트패턴 = /(?<![\w가-힣./-])([가-힣A-Za-z_][\w가-힣]*\.(?:py|sh|ps1))(?![\w가-힣])/g;
    /* 스크립트가 사는 곳 — 부모의 두 도구함. ⚠ 목록을 늘릴 땐 **실재하는 디렉터리만** 넣어라
       (없는 곳을 넣으면 이 검사가 조용히 관대해진다). */
    const 도구함 = ['pipeline/_도구', 'survey/_도구'];
    const 표 = new Map<string, Set<string>>();
    for (const { path, code } of sources()) {
      for (const m of code.matchAll(스크립트패턴)) {
        const 이름 = m[1]!;
        if (!표.has(이름)) 표.set(이름, new Set());
        표.get(이름)!.add(
          path
            .slice(SRC.length + 1)
            .split(sep)
            .join('/'),
        );
      }
    }
    const 없는것 = [...표]
      .filter(([이름]) => !도구함.some((d) => existsSync(join(워크스페이스, d, 이름))))
      .map(([이름, 파일들]) => `${이름}  ← ${[...파일들].sort().join(', ')}`)
      .sort();

    expect(없는것, '화면이 없는 스크립트를 치라고 시킨다 — 사용자는 셸에서 «파일 없음» 을 받는다').toEqual([]);
  });
});
