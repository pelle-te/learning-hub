/* ============================================================
   ledgerRules.test.ts — 기한부 판단 원장의 **세 규칙**을 잠근다(V078·V096 · 2026-09-01).

   ## 왜 유닛인가 — 되심기를 영구화한 것

   이 규칙의 소비처는 `e2e/a11y.spec.ts`(Playwright · 94화면 · 수 분)와
   `scripts/freshness.mjs`(네트워크 · `gh`)다. 둘 다 **되심기가 비싸고 환경에 의존**한다.
   그런데 규칙 자체는 **순수 함수**라 여기서 초 단위로 전량 대조할 수 있다 —
   `src-tauri/src/testkit.rs` 머리주석이 못박은 규율과 같다: *"실물이 필요하면 통합, 아니면 유닛."*

   ⭐ 그래서 이 파일이 곧 **되심기의 영구 형태**다. 세 규칙 각각에 대해 「어겼을 때 빨간불인가」를
   케이스로 들고 있으므로, 다음 회차가 판정을 고치다 한 규칙을 죽이면 **여기가 먼저 운다.**

   ⚠ **`ok: true` 만 확인하는 케이스를 쓰지 마라** — 이 저장소가 반복해 물린 것이 「0건인데
   아무것도 안 쟀다」다. 아래는 전부 **위반을 만들어 두고 그것이 잡히는지**를 본다.
============================================================ */
import { describe, expect, it } from 'vitest';
import { 원장판정, 원장메시지 } from '../scripts/ledger-rules.mjs';

const 항목 = (재검토: string) => ({ 사유: '되심기', 재검토 });
const 오늘 = '2026-09-01';

describe('기한부 판단 원장 — 세 규칙 (V078·V096)', () => {
  it('유효한 면제는 통과하고 `적용` 에 실린다', () => {
    const r = 원장판정({ 원장: { 'a :: x': 항목('2099-01-01') }, 상태: { 'a :: x': true }, 오늘 });
    expect(r.ok).toBe(true);
    expect(r.적용).toEqual(['a :: x']); // 호출부가 이만큼 삼켜도 된다
  });

  it('② 만료 — 재검토일이 지났는데 아직 위반이면 실패', () => {
    const r = 원장판정({ 원장: { 'b :: y': 항목('2020-01-01') }, 상태: { 'b :: y': true }, 오늘 });
    expect(r.ok).toBe(false);
    expect(r.만료).toEqual(['b :: y']);
    expect(r.적용).toEqual([]); // ⚠ 만료된 면제는 **삼키지 않는다**
  });

  it('③ 역래칫 — 위반이 사라졌는데 원장에 남아 있으면 실패', () => {
    /* ⚠⚠ **이 규칙이 `a11y.spec.ts` 에만 없었다**(V078). 없으면 고친 뒤에도 항목이 남고,
       `원장적용` 이 그 화면·그 규칙의 위반을 전부 삼키므로 **새 위반이 그 아래로 조용히
       들어간다** — 원장이 규칙을 끈 것과 같아지는 경로다. */
    const r = 원장판정({ 원장: { 'c :: z': 항목('2099-01-01') }, 상태: { 'c :: z': false }, 오늘 });
    expect(r.ok).toBe(false);
    expect(r.사문).toEqual(['c :: z']);
  });

  it('관측하지 않은 키는 판정을 보류한다 — 「모른다」를 「해소됐다」로 읽지 않는다', () => {
    /* ⚠ 이 줄이 없으면 반대로 무너진다: 어떤 이유로 그 화면을 안 돈 회차가 원장을 **통째로
       사문 처리**해서, 사람이 시키는 대로 지우면 다음 회차에 위반이 되살아난다.
       `freshness.mjs` 가 «관측 불가는 실패가 아니다 — 다만 조용히 건너뛰지는 않는다»로 적은
       규율과 같은 자리다. */
    const r = 원장판정({ 원장: { 'd :: w': 항목('2099-01-01') }, 상태: {}, 오늘 });
    expect(r.ok).toBe(true);
    expect(r.사문).toEqual([]);
    expect(r.적용).toEqual([]); // 보류이지 «유효한 면제»도 아니다
  });

  it('둘이 동시에 나면 둘 다 보고한다 (첫 건에서 멈추지 않는다)', () => {
    const 원장 = { 'b :: y': 항목('2020-01-01'), 'c :: z': 항목('2099-01-01') };
    const r = 원장판정({ 원장, 상태: { 'b :: y': true, 'c :: z': false }, 오늘 });
    expect(r.만료).toEqual(['b :: y']);
    expect(r.사문).toEqual(['c :: z']);
    const msg = 원장메시지('되심기', r, 원장);
    // 메시지가 **무엇을 하면 되는지**까지 말해야 한다(이 저장소의 에러 메시지 규율).
    expect(msg).toContain('b :: y');
    expect(msg).toContain('c :: z');
    expect(msg).toContain('역래칫');
  });

  it('빈 원장은 통과한다 — 그리고 그것이 정상 상태다', () => {
    expect(원장판정({ 원장: {}, 상태: { 'a :: x': true }, 오늘 }).ok).toBe(true);
  });
});
